"""Google AlphaEarth Satellite Embeddings dataset module for Google Earth Engine integration.

This module provides the GEEAlphaEarth class for accessing Google AlphaEarth Satellite
Embedding data from Google Earth Engine, which provides global, analysis-ready
64-dimensional embedding vectors for land and shallow water pixels.
"""

from typing import Any, Callable, Dict, Optional, Tuple

import ee

from rasterio.crs import CRS
from torchgeo.datasets import BoundingBox

from .geebase import GEERasterDataset


class GEEAlphaEarth(GEERasterDataset):
    """Google AlphaEarth Satellite Embeddings Earth Engine Collection.

    This dataset provides global, analysis-ready 64-dimensional embedding vectors for each
    10m land and shallow water pixel. Unlike raw spectral data, these embeddings summarize
    complex, multi-source Earth observation data (optical, radar, LiDAR) over a full calendar
    year, capturing temporal surface condition trajectories. Covering ~164km x 164km tiles in
    UTM projection, the unit-length vectors are distributed on a sphere. Key features include
    consistency across years (enabling change detection via vector similarity), linear
    composability for aggregation, and robustness to common issues like clouds and missing
    data. Generated by the AlphaEarth Foundations model, they are designed for direct use in
    segmentation, regression, and change detection analyses.

    Dataset Bands (A00-A63):
        A00-A63: 64-dimensional embedding vectors (unit-length, distributed on a sphere)

    Spatial Resolution: 10 meters

    Temporal Coverage: Annual (full calendar year)

    References:
        Google Research. AlphaEarth: Satellite Embeddings for Earth Observation.
        https://developers.google.com/earth-engine/datasets/catalog/GOOGLE_SATELLITE_EMBEDDING_V1_ANNUAL
    """

    filename_glob = "*.tif"

    gee_asset_id = "GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL"

    all_bands = [f"A{i:02d}" for i in range(64)]

    rgb_bands = ["A01", "A16", "A09"]

    nodata = 0

    instrument = "AlphaEarth"

    is_image = True

    def __init__(
        self,
        year: int,
        roi: Optional[BoundingBox] = None,
        res: float = 10,
        bands: Optional[Tuple[str, ...]] = None,
        path: Optional[str] = None,
        crs: Optional[CRS] = CRS.from_epsg(5070),
        transforms: Callable[[Dict[str, Any]], Dict[str, Any]] | None = None,
        download: bool = False,
        overwrite: bool = False,
        cache: bool = True,
    ) -> None:
        """Initialize a GEEAlphaEarth dataset instance.

        Args:
            year (int): The year of the dataset to retrieve embeddings for.
            roi (BoundingBox, optional): Region of interest to fetch data from.
            res (float, optional): Resolution of the dataset in meters. Defaults to 10.
            bands (Tuple[str, ...], optional): List of bands to select from the dataset.
                If not provided, defaults to ["A01", "A16", "A09"].
            path (str, optional): Directory where data are stored or will be stored if download
                is True. If path is provided and a matching file exists, the image will be
                loaded from that file unless overwrite is True.
            crs (CRS, optional): Coordinate Reference System for fetching images from
                Earth Engine. Defaults to EPSG:5070.
            transforms (Callable, optional): Function/transform that takes in a sample
                and returns a transformed version.
            download (bool, optional): If True, download the dataset to the path directory.
                Defaults to False.
            overwrite (bool, optional): If True, overwrite the dataset if it already exists.
                Defaults to False.
            cache (bool, optional): If True, cache the dataset in memory. Defaults to True.
        """
        super().__init__(
            roi=roi,
            path=path,
            crs=crs,
            transforms=transforms,
            download=download,
            overwrite=overwrite,
            cache=cache,
        )
        self.res = res
        self.bands = bands or self.rgb_bands
        self.filename_suffix = f"_{year}"
        self.date_start = f"{year}-01-01"
        self.date_end = f"{year + 1}-01-01"

    @property
    def collection(self) -> ee.ImageCollection:
        """Get the Earth Engine image collection with selected bands and date filter.

        Returns:
            ee.ImageCollection: Filtered AlphaEarth image collection for the specified year
                with selected bands.
        """
        return (
            ee.ImageCollection(self.gee_asset_id)
            .filterDate(self.date_start, self.date_end)
            .select(self.bands)
        )

    def _reducer(self, collection: ee.ImageCollection) -> ee.Image:
        """Reduce image collection to a single image using median composite.

        Args:
            collection (ee.ImageCollection): Earth Engine image collection to reduce.

        Returns:
            ee.Image: Median composite image from the collection.

        Note:
            For AlphaEarth embeddings, which are already processed annual composites,
            the median operation aggregates any duplicate observations within the
            specified date range. The embeddings are designed to be temporally consistent
            across years.
        """
        return collection.median()

    def _preprocess(self, image: ee.Image) -> ee.Image:
        """Preprocess AlphaEarth image.

        Note:
            This method is only to bypass abstract method requirement.
            No preprocessing is needed for AlphaEarth embeddings as they are already
            analysis-ready vectors generated by the AlphaEarth Foundations model.
        """
        pass
